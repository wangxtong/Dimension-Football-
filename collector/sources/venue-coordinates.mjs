export function venueFor(team) {
  if (typeof team !== 'string' || !team.trim()) return null;
  const name = team.trim();
  const direct = VENUES[name];
  if (direct) return { team: name, ...direct };
  const alias = VENUE_ALIASES[name];
  return alias && VENUES[alias] ? { team: alias, ...VENUES[alias] } : null;
}

export function venueCount() { return Object.keys(VENUES).length; }
